export function getEditorMusicTrackByUrl(audioUrl: string) {
  return editorMusicTracks.find((track) => {
    if (track.audioUrl === audioUrl) {
      return true;
    }

    // Compat: old Pixabay CDN URLs and new first-party catalog paths.
    return (
      audioUrl === `/api/catalog-music/${track.id}` ||
      audioUrl.endsWith(`/catalog-music/${track.id}.mp3`)
    );
  });
}

export function getTemplateMusicPreset(templateId: string) {
  const track =
    musicTrackById.get(
      templateMusicTrackIds[templateId] ?? templateMusicTrackIds["alpine-rings"],
    ) ?? editorMusicTracks[0];

  return {
    musicEnabled: true,
    musicTitle: track.title,
    musicUrl: track.audioUrl,
  };
}
